import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(new URL('../artifacts/api-server/package.json', import.meta.url));
const { build } = require('esbuild');
const output = new URL('../artifacts/api-server/.local/profile-tests/local-game.mjs', import.meta.url);
await build({ entryPoints:[fileURLToPath(new URL('../artifacts/card-game/src/lib/localGame.ts',import.meta.url))],outfile:fileURLToPath(output),bundle:true,platform:'node',format:'esm' });
const { localPlayer, localLobby, startLocal, playLocal, advanceLocal, localView } = await import(output.href);
for(let count=2;count<=10;count++) {
  const state=startLocal({...localLobby(Array.from({length:count},(_,i)=>localPlayer(`p${i}`,`Player ${i}`))),dealerId:'p0'});
  assert.equal(state.players.length,count);
  assert.equal(state.players.reduce((sum,p)=>sum+p.hand.length,0),52);
  assert.ok(Math.max(...state.players.map(p=>p.hand.length))-Math.min(...state.players.map(p=>p.hand.length))<=1);
  const view=localView(state,'p0');
  assert.deepEqual(view.players[0].hand,state.players[0].hand);
  assert.ok(view.players.slice(1).every(p=>p.hand.length===0));
  assert.throws(()=>playLocal(state,'intruder',{rank:'A',suit:'spades'}));
}
const h=rank=>({rank,suit:'hearts'}), s=rank=>({rank,suit:'spades'});
let state=localLobby(['one','two','three'].map(id=>localPlayer(id,id)));
Object.assign(state,{phase:'playing',roundNumber:2,currentTurn:'one'});
state.players[0].hand=[h('3'),h('2')];state.players[1].hand=[h('K'),h('4')];state.players[2].hand=[s('A'),s('2')];
state=playLocal(state,'one',h('3'));
assert.throws(()=>playLocal(state,'three',s('A')));
state=playLocal(state,'two',h('K'));
state=playLocal(state,'three',s('A'));
assert.equal(state.phase,'round_end');assert.equal(state.roundWinnerId,'two');assert.equal(state.players[1].hand.length,4);
state=advanceLocal(state);assert.equal(state.currentTurn,'two');assert.equal(state.roundCards.length,0);
let end=localLobby(['one','two'].map(id=>localPlayer(id,id)));
Object.assign(end,{phase:'playing',roundNumber:2,currentTurn:'one'});
end.players[0].hand=[h('A')];end.players[1].hand=[h('3'),s('2')];
end=playLocal(playLocal(end,'one',h('A')),'two',h('3'));
assert.equal(end.phase,'game_over');assert.equal(end.currentGameWinnerId,'one');assert.equal(end.gameOverLoserId,'two');
assert.deepEqual(end.penaltyCard,s('A'));
const next=startLocal(localLobby(end.players,end.gameId,end));
assert.ok(next.players.every(p=>p.hand.every(c=>c.rank!=='A'||c.suit!=='spades')));
assert.deepEqual(next.players[1].penaltyCards,[s('A')]);
assert.throws(()=>startLocal(localLobby([localPlayer('one','one')])));
console.log('PASS local games: 2-10 players, hidden hands, turn validation, immediate lead-suit pickup, round advance, winner/loser, persistent locked penalties');
