import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomBytes, createHash } from 'node:crypto';
const require = createRequire(new URL('../artifacts/api-server/package.json', import.meta.url));
const { build } = require('esbuild');
const output = new URL('../artifacts/api-server/.local/profile-tests/manager.mjs', import.meta.url);
await build({ entryPoints: [fileURLToPath(new URL('../artifacts/api-server/src/lib/gameManager.ts', import.meta.url))], outfile: fileURLToPath(output), bundle: true, platform: 'node', format: 'esm', packages: 'external' });
process.env.NODE_ENV = 'production';
process.env.LOG_LEVEL = 'silent';
const fixtureDir = mkdtempSync(join(tmpdir(), 'donkey-voice-'));
process.env.ACCOUNTS_FILE = join(fixtureDir, 'accounts.json');
const tokens = Array.from({length:3}, () => randomBytes(32).toString('hex'));
writeFileSync(process.env.ACCOUNTS_FILE, JSON.stringify({
  users: tokens.map((_,i)=>({id:String(i),username:`voice_fixture_${i}`,salt:'',hash:''})),
  sessions: tokens.map((token,i)=>({hash:createHash('sha256').update(token).digest('hex'),userId:String(i),expires:Date.now()+60000})),
  friends:[],requests:[],
}));
process.on('exit',()=>rmSync(fixtureDir,{recursive:true,force:true}));
const { handleMessage, handleDisconnect } = await import(output.href);
const socket = () => ({ readyState: 1, messages: [], send(data) { this.messages.push(JSON.parse(data)); } });
const send = (client, type, payload) => handleMessage(client, JSON.stringify({ type, payload }));
const latest = (client, type) => client.messages.filter(m => m.type === type).at(-1)?.payload;
const host = socket(), guest = socket(), outsider = socket();
[host,guest,outsider].forEach((client,i)=>send(client,'authenticate',{token:tokens[i]}));
// Header/trailer fixture exercises transport validation, not image decoding.
const photo = 'data:image/jpeg;base64,/9j/2Q==';
send(host, 'create_game', { playerName: 'Host', avatarUrl: photo });
const { gameId, playerId } = latest(host, 'joined');
send(guest, 'join_game', { gameId, playerName: 'Guest' });
assert.equal(latest(guest, 'game_state').players[0].avatarUrl, photo);
send(host, 'update_profile', { gameId, playerName: 'Updated', avatarUrl: null });
assert.equal(latest(guest, 'game_state').players.find(p => p.id === playerId).name, 'Updated');
assert.equal(latest(guest, 'game_state').players[0].avatarUrl, null);
send(host, 'update_profile', { gameId, playerName: 'Host', avatarUrl: 'javascript:alert(1)' });
assert.ok(latest(host, 'error'));
assert.equal(latest(guest, 'game_state').players[0].name, 'Updated');
send(host, 'update_profile', { gameId, playerName: 'Host', avatarUrl: photo });
send(host, 'restart_tournament', { gameId });
assert.equal(latest(guest, 'game_state').players[0].avatarUrl, photo);
send(outsider, 'create_game', { playerName: 'Other room' });
send(outsider, 'update_profile', { gameId, playerName: 'Spoof', avatarUrl: null });
assert.equal(latest(outsider, 'error').message, 'You are not in this game');
console.log('PASS profiles: shared, removable, validated, room-scoped, retained across restart');
const chunk = { gameId, mimeType: 'audio/webm', data: 'AAAA' };
send(host, 'voice_join', { gameId });
send(host, 'voice_chunk', chunk);
assert.equal(latest(guest, 'voice_chunk'), undefined);
send(guest, 'voice_join', { gameId });
for (let i=0; i<130; i++) send(host, 'voice_chunk', chunk);
assert.equal(guest.messages.filter(m => m.type === 'voice_chunk').length, 130);
assert.equal(latest(outsider, 'voice_chunk'), undefined);
send(guest, 'voice_leave', { gameId });
send(host, 'voice_chunk', chunk);
assert.equal(guest.messages.filter(m => m.type === 'voice_chunk').length, 130);
send(guest, 'voice_chunk', chunk);
assert.equal(latest(host, 'voice_chunk'), undefined);
console.log('PASS voice relay: opt-in only, same room only, leave stops transmission/reception, 130 chunks');
const guestId = latest(guest, 'joined').playerId;
const offer = { type: 'offer', description: { type: 'offer', sdp: 'v=0' } };
const relay = () => send(host, 'voice_signal', { gameId, toPlayerId: guestId, signal: offer });
relay();
assert.equal(latest(guest, 'voice_signal'), undefined);
send(guest, 'voice_join', { gameId });
relay();
assert.equal(latest(guest, 'voice_signal').fromPlayerId, playerId);
const count = guest.messages.filter(m => m.type === 'voice_signal').length;
send(outsider, 'voice_signal', { gameId, toPlayerId: guestId, signal: offer });
send(host, 'voice_signal', { gameId, toPlayerId: guestId, signal: { type: 'offer', description: { type: 'answer', sdp: 'v=0' } } });
send(host, 'voice_signal', { gameId, toPlayerId: guestId, signal: { type: 'offer', description: { type: 'offer', sdp: 'x'.repeat(33000) } } });
assert.equal(guest.messages.filter(m => m.type === 'voice_signal').length, count);
send(host, 'voice_leave', { gameId });
relay();
assert.equal(guest.messages.filter(m => m.type === 'voice_signal').length, count);
console.log('PASS RTC signaling: opt-in sender/receiver, room isolation, shape/size limits, leave stops signaling');
send(host, 'voice_join', { gameId });
send(host, 'voice_music', { gameId, title: 'Shared.mp3', playing: true });
assert.equal(latest(guest, 'voice_music').title, 'Shared.mp3');
assert.equal(latest(guest, 'voice_music').playing, true);
assert.equal(latest(outsider, 'voice_music'), undefined);
send(guest, 'voice_music', { gameId, title: 'Guest.mp3', playing: true });
assert.equal(latest(guest, 'error').message, 'Only the room host can control shared songs');
assert.equal(latest(host, 'voice_music').title, 'Shared.mp3');
send(outsider, 'voice_music', { gameId, title: 'Other.mp3', playing: true });
assert.equal(latest(host, 'voice_music').title, 'Shared.mp3');
send(host, 'voice_music', { gameId, title: 'x'.repeat(161), playing: true });
assert.equal(latest(host, 'error').message, 'Invalid message payload');
send(host, 'voice_music', { gameId, title: 'Shared.mp3', playing: false });
assert.equal(latest(guest, 'voice_music').playing, false);
send(guest, 'voice_leave', { gameId });
send(guest, 'voice_join', { gameId });
assert.equal(latest(guest, 'voice_music').title, 'Shared.mp3');
send(host, 'voice_leave', { gameId });
assert.equal(latest(guest, 'voice_music').title, '');
send(host, 'voice_music', { gameId, title: 'Shared.mp3', playing: true });
assert.equal(latest(host, 'error').message, 'Join room audio first');
send(host, 'voice_join', { gameId });
send(host, 'voice_music', { gameId, title: 'Shared.mp3', playing: true });
handleDisconnect(host);
assert.equal(latest(guest, 'voice_music').title, '');
console.log('PASS room music: host-only controls, validation, room isolation, late listener snapshot, pause, host leave/disconnect cleanup');
