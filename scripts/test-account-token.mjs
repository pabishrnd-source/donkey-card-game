import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const require = createRequire(new URL('../artifacts/api-server/package.json', import.meta.url));
const { build } = require('esbuild');
const result = await build({entryPoints:[fileURLToPath(new URL('../artifacts/card-game/src/lib/accountToken.ts',import.meta.url))],bundle:true,platform:'node',format:'esm',write:false});
const source = 'data:text/javascript;base64,' + Buffer.from(result.outputFiles[0].text).toString('base64');
let stored = 'saved-session';
globalThis.window = {localStorage:{getItem:()=>stored,setItem:(_key,value)=>{stored=value;},removeItem:()=>{stored=null;}}};
const normal = await import(source+'#normal');
assert.equal(normal.readAccountToken(),'saved-session');
normal.saveAccountToken('new-session');
assert.equal(stored,'new-session');
normal.saveAccountToken(null);
assert.equal(stored,null);
const blocked = await import(source+'#blocked');
Object.defineProperty(window,'localStorage',{configurable:true,get(){throw new Error('Storage blocked');}});
assert.equal(blocked.readAccountToken(),null);
assert.doesNotThrow(()=>blocked.saveAccountToken('memory-session'));
assert.equal(blocked.readAccountToken(),'memory-session');
assert.doesNotThrow(()=>blocked.saveAccountToken(null));
assert.equal(blocked.readAccountToken(),null);
Object.defineProperty(window,'localStorage',{value:{getItem:()=> 'stale-session',setItem(){throw new Error('Quota exceeded');},removeItem(){throw new Error('Blocked');}}});
const full = await import(source+'#full');
assert.equal(full.readAccountToken(),'stale-session');
full.saveAccountToken('replacement');
assert.equal(full.readAccountToken(),'replacement');
full.saveAccountToken(null);
assert.equal(full.readAccountToken(),null);
console.log('PASS account tokens: persistence, blocked storage, quota errors, in-memory reconnect and logout without stale-token reuse');
